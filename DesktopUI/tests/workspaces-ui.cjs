const { _electron: electron } = require("playwright");
const fs = require("node:fs/promises"), path = require("node:path"), assert = require("node:assert/strict");
const { artifactPath } = require("./fixtures/artifacts.cjs");
const { worldDataFixture } = require("./fixtures/world-data.cjs");
const { WorkspaceStore } = require("../electron/services.cjs");
const { Profiles } = require("../electron/domains/profiles/profiles.cjs");
const { WorldLibrary } = require("../electron/domains/worlds/worlds.cjs");
(async () => {
  let app;
  try {
    const root = artifactPath("ui"), data = path.join(root, "data"), source = path.join(root, "source"), other = path.join(root, "other");
    await worldDataFixture(source); await worldDataFixture(other, { changed: true });
    const store = new WorkspaceStore(data); await store.load(); const profiles = new Profiles(store); await profiles.initialize();
    const worlds = new WorldLibrary(store, path.join(data, "game-data/MinecraftPE_Netease/minecraftWorlds"));
    const world = await worlds.create(store.value.projects[0].id, { name: "工作区示例" }); await worldDataFixture(worlds.location(world.id));
    const env = { ...process.env, DGN_GAME_HEADLESS: "1", DGN_GAME_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
    app = await electron.launch({ executablePath: process.env.DGN_GAME_TEST_EXE || undefined, args: process.env.DGN_GAME_TEST_EXE ? [] : ["."], env });
    const page = await app.firstWindow(); page.setDefaultTimeout(15000); await page.emulateMedia({ reducedMotion: "reduce" });
    const errors = []; page.on("pageerror", e => errors.push(e.message));
    const ipc = (method, args = {}) => page.evaluate(({ method, args }) => window.toolkit.call(method, args), { method, args });
    await assert.rejects(ipc("world-data.scan", { source, requestId: "unselected-data" }), /选择|授权/);
    const initialProfiles = await ipc("profiles.list");
    await app.evaluate(({ dialog, BrowserWindow }, source) => {
      BrowserWindow.getAllWindows()[0].webContents.setBackgroundThrottling(false);
      globalThis.fixtureSource = source;
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [globalThis.fixtureSource] });
    }, source);
    await page.getByRole("heading", { name: "存档", exact: true }).waitFor();
    assert.equal(await page.locator(".sidebar nav button").count(), 7);
    const nav = async name => { await page.locator(".sidebar").getByRole("button", { name, exact: true }).click(); await page.waitForFunction(() => !document.documentElement.dataset.pageAnimating); };
    await page.getByRole("button", { name: "打开外部存档", exact: true }).click();
    await page.getByRole("navigation", { name: "存档工作区" }).getByRole("button", { name: "世界数据", exact: true }).click();
    await page.getByRole("button", { name: "选择外部文件夹", exact: true }).click();
    await page.getByRole("button", { name: "扫描已保存数据", exact: true }).click();
    await page.getByText("受支持记录扫描完成", { exact: true }).waitFor({ timeout: 60000 });
    for (const [label, extension] of [["导出 JSON", "json"], ["导出当前类型 CSV", "csv"], ["导出关系图", "svg"]]) {
      const target = path.join(root, "export." + extension);
      await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }); }, target);
      await page.getByRole("button", { name: label, exact: true }).click();
      await page.waitForTimeout(100);
      const text = await fs.readFile(target, "utf8"); assert(text.length > 20);
      if (extension === "json") assert(JSON.parse(text).objects.length > 0);
      if (extension === "svg") assert(text.startsWith("<svg"));
    }
    await page.getByRole("textbox", { name: "搜索世界数据" }).fill("9223372036854775807");
    await page.locator(".data-results > button").first().click();
    await page.getByRole("button", { name: "在地图定位", exact: true }).click();
    await page.getByLabel("地图画布").waitFor();
    await page.locator(".map-preview-status").first().getByText(/范围 X/).waitFor({ timeout: 60000 });
    await page.getByRole("navigation", { name: "存档工作区" }).getByRole("button", { name: "世界数据", exact: true }).click();
    assert.equal(await page.getByRole("textbox", { name: "搜索世界数据" }).inputValue(), "9223372036854775807");
    await page.getByRole("textbox", { name: "搜索世界数据" }).fill("");
    await app.evaluate((_, other) => { globalThis.fixtureSource = other; }, other);
    await page.getByRole("button", { name: "比较另一目录", exact: true }).click();
    await page.getByText(/处对象变化/).waitFor({ timeout: 60000 });
    assert(await page.getByText(/字段变化.*采集任务/).count());
    const diffTarget = path.join(root, "comparison.json");
    await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }); }, diffTarget);
    await page.getByRole("button", { name: "导出差异 JSON", exact: true }).click();
    await page.waitForTimeout(100); assert(JSON.parse(await fs.readFile(diffTarget, "utf8")).changes.length > 0);
    await nav("设置"); await nav("存档");
    await page.getByRole("heading", { name: "外部存档查看", exact: true }).waitFor();
    await page.getByRole("button", { name: "返回存档列表", exact: true }).click();
    await page.getByRole("button", { name: "工作区示例", exact: true }).click();
    await page.getByRole("navigation", { name: "存档工作区" }).getByRole("button", { name: "模组", exact: true }).click();
    await page.getByRole("heading", { name: "存档模组：工作区示例", exact: true }).waitFor();
    assert.equal(await page.locator("dialog[open]").count(), 0);
    await page.getByRole("button", { name: "地形与建筑导入", exact: true }).click();
    await page.getByRole("heading", { name: "地形与建筑导入", exact: true }).waitFor();
    assert.equal(await page.locator("dialog[open]").count(), 0);
    await nav("运行与调试");
    await page.getByRole("navigation", { name: "工作区工具" }).getByRole("button", { name: "控制台", exact: true }).click();
    await page.getByRole("button", { name: "启动空白客户端", exact: true }).waitFor();
    await nav("模组与资源"); await page.getByRole("navigation", { name: "工作区工具" }).getByRole("button", { name: "UI 编辑器", exact: true }).click();
    await page.locator(".ue-editor, .ui-editor, .ue-workspace").first().waitFor().catch(() => page.getByRole("button", { name: "新建", exact: true }).waitFor());
    await nav("存档");
    await page.getByRole("heading", { name: "工作区示例", exact: true }).waitFor();
    await page.getByRole("navigation", { name: "存档工作区" }).getByRole("button", { name: "世界数据", exact: true }).click();
    await page.getByRole("button", { name: "扫描已保存数据", exact: true }).click();
    await page.getByText("受支持记录扫描完成", { exact: true }).waitFor();
    await page.getByRole("combobox", { name: "数据视图", exact: true }).click();
    await page.getByRole("option", { name: "对象与字段", exact: true }).click();
    await page.locator(".data-layout").waitFor();
    await page.waitForFunction(() => !document.querySelector(":popover-open"));
    for (const [theme, width, height] of [["light", 1240, 820], ["dark", 900, 650]]) {
      await page.evaluate(theme => window.toolkit.call("settings.update", { AppearanceMode: theme === "light" ? "Light" : "Dark" }), theme);
      await page.waitForFunction(theme => document.documentElement.dataset.theme === theme, theme);
      await app.evaluate(({ BrowserWindow }, args) => { BrowserWindow.getAllWindows()[0].setSize(args.width, args.height); }, { width, height });
      await page.waitForFunction(() => {
        const button = document.querySelector(".world-context .button:not(.primary)");
        const text = getComputedStyle(document.body).color;
        return button && getComputedStyle(button).color === text;
      });
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "horizontal overflow");
      const bytes = await app.evaluate(async ({ BrowserWindow }) => {
        const contents = BrowserWindow.getAllWindows()[0].webContents;
        await contents.capturePage(undefined, { stayHidden: true, stayAwake: true });
        await new Promise(resolve => setTimeout(resolve, 100));
        return (await contents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString("base64");
      });
      await fs.writeFile(artifactPath("outputs/workspace-" + theme + ".png"), Buffer.from(bytes, "base64"));
    }
    const after = await page.evaluate(() => window.toolkit.call("worlds.list"));
    assert.equal(after.worlds.length, 1, "external reads must not register worlds");
    assert.equal((await ipc("profiles.list")).length, initialProfiles.length, "external reads must not create profiles");
    assert((await ipc("activity.snapshot")).tasks.some(task => task.method === "world-data.scan" && task.status === "success"));
    await nav("任务与记录");
    assert.equal(await page.getByRole("region", { name: "进行中的任务", exact: true }).locator(".activity-task.success").count(), 0);
    await page.getByRole("region", { name: "失败与中断", exact: true }).waitFor();
    assert(await page.getByRole("region", { name: "失败与中断", exact: true }).locator(".activity-task.failed").count());
    assert.equal(await page.locator(".activity-history").getAttribute("open"), null);
    await page.locator(".activity-history summary").click();
    assert(await page.locator(".activity-history .activity-task.success").count());
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.setZoomFactor(1.25));
    await page.waitForTimeout(100);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "125% zoom horizontal overflow");
    assert.deepEqual(errors, []);
    console.log("Workspace navigation, external data, compare, map locate, page persistence and narrow layout passed");
  } finally { if (app) await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
