const { _electron: electron } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { artifactPath, artifactRoot } = require("./fixtures/artifacts.cjs");

(async () => {
  const data = artifactPath("data"), folder = path.join(data, "model-studio", "batch");
  await fs.mkdir(folder, { recursive: true });
  await fs.writeFile(path.join(folder, "model.geo.json"), JSON.stringify({ "minecraft:geometry": [{ description: { identifier: "geometry.batch", texture_width: 64, texture_height: 64 }, bones: [{ name: "body", pivot: [0, 6, 0], cubes: [{ origin: [-4, 0, -2], size: [8, 12, 4], uv: [0, 0] }] }] }] }), "utf8");
  const expression = { pre: [1, 2, 3], post: ["q.anim_time * 20", 0, 0], lerp_mode: "catmullrom", extra: "keep" };
  const source = { loop: false, animation_length: 3, sound_effects: { "0": { effect: "fixture" } }, bones: { body: { rotation: { "0": [0, 0, 0], "0.5": expression, "1.00": [10, 20, 30] }, position: { "0.00": [0, 1, 0] } } } };
  const file = path.join(folder, "model.animation.json");
  await fs.writeFile(file, JSON.stringify({ animations: { "animation.batch": source } }, null, 2), "utf8");
  const env = { ...process.env, DGN_GAME_HEADLESS: "1", DGN_GAME_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ cwd: path.join(__dirname, ".."), env, ...(process.env.DGN_GAME_TEST_EXE ? { executablePath: process.env.DGN_GAME_TEST_EXE, args: [] } : { args: ["."] }) });
  let page;
  const errors = [];
  const read = async () => JSON.parse(await fs.readFile(file, "utf8")).animations["animation.batch"];
  try {
    page = await app.firstWindow(); page.setDefaultTimeout(15000);
    page.on("pageerror", error => errors.push(error.message));
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 900));
    await page.getByRole("heading", { name: "存档", exact: true }).waitFor();
    await page.getByRole("button", { name: "模组与资源", exact: true }).click();
    await page.getByRole("button", { name: "模型制作", exact: true }).click();
    await page.locator(".model-library-open").filter({ hasText: "geometry.batch" }).click();
    await page.getByRole("button", { name: "动画", exact: true }).click();
    await page.getByRole("button", { name: "animation.batch", exact: true }).click();
    await page.locator(".model-bone-list").getByRole("button", { name: "body", exact: true }).click();
    const timeline = page.locator(".model-timeline");
    const frame = time => timeline.getByRole("button", { name: "关键帧 旋转 " + time.toFixed(2), exact: true });
    const count = value => page.waitForFunction(value => document.querySelector('[aria-label="关键帧选择"]').textContent === "已选 " + value + " 帧", value);
    const saved = async (message) => {
      await page.getByText(message, { exact: true }).waitFor();
      await page.waitForFunction(() => !document.querySelector('[aria-label="关键帧选择"]').textContent.includes("保存中"));
    };
    await frame(0).click(); await frame(0.5).click({ modifiers: ["Control"] }); await count(2);
    assert.equal(await frame(0).getAttribute("aria-pressed"), "true");
    assert.equal(await frame(0.5).getAttribute("aria-pressed"), "true");
    await frame(0.5).click({ modifiers: ["Control"] }); await count(1);
    await frame(0).click({ modifiers: ["Control"] }); await count(0);
    assert.equal(await timeline.getByRole("button", { name: "复制", exact: true }).isDisabled(), true);
    await frame(0).click(); await frame(1).click({ modifiers: ["Shift"] }); await count(3);
    await page.screenshot({ path: artifactPath("outputs/multiselect-1440.png") });
    await frame(0).click(); await frame(0.5).click({ modifiers: ["Control"] }); await count(2);
    await page.getByLabel("关键帧偏移秒数").fill("0.50");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click();
    await page.getByText("目标时间已有关键帧，未覆盖任何帧", { exact: true }).waitFor();
    assert.deepEqual(await read(), source);
    await page.getByLabel("关键帧偏移秒数").fill("-0.25");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click();
    await page.getByText("关键帧时间必须在 0–10000 秒之间", { exact: true }).waitFor();
    assert.deepEqual(await read(), source);
    await page.getByLabel("关键帧偏移秒数").fill("0.25");
    // 真实文件写入失败：备份路径被测试目录占用，不替换 IPC 或产品错误处理。
    await fs.mkdir(file + ".bak");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click();
    await page.getByText(/EISDIR|EPERM|illegal operation|operation not permitted/).waitFor();
    assert.deepEqual(await read(), source);
    assert.equal(await frame(0).count(), 1); await count(2);
    assert.equal(await timeline.getByRole("button", { name: "撤销", exact: true }).isDisabled(), true);
    await fs.rmdir(file + ".bak");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click(); await saved("已移动 2 个关键帧");
    assert.deepEqual(Object.keys((await read()).bones.body.rotation).map(Number).sort(), [0.25, 0.75, 1]);
    assert.deepEqual((await read()).bones.body.rotation["0.75"], expression);
    await timeline.getByRole("button", { name: "撤销", exact: true }).click(); await saved("已撤销");
    assert.deepEqual(await read(), source);
    await timeline.getByRole("button", { name: "重做", exact: true }).click(); await saved("已重做");
    await frame(0.25).click(); await frame(0.75).click({ modifiers: ["Control"] }); await count(2);
    await timeline.getByRole("button", { name: "复制", exact: true }).click();
    const slider = page.getByRole("slider", { name: "时间", exact: true });
    await slider.press("Home"); for (let i = 0; i < 30; i++) await slider.press("ArrowRight");
    await timeline.getByRole("button", { name: "粘贴", exact: true }).click(); await saved("已粘贴 2 个关键帧");
    assert.deepEqual((await read()).bones.body.rotation["2.00"], expression);
    await timeline.getByRole("button", { name: "删除所选", exact: true }).click(); await saved("已删除 2 个关键帧");
    assert.equal((await read()).bones.body.rotation["2.00"], undefined);
    await frame(0.25).click(); await frame(0.75).click({ modifiers: ["Control"] }); await count(2);
    const point = await frame(0.25).boundingBox();
    const track = await frame(0.25).locator("..").boundingBox();
    await page.mouse.move(point.x + point.width / 2, point.y + point.height / 2); await page.mouse.down();
    await page.mouse.move(point.x + point.width / 2 - (track.width - 12) * 0.25 / 3, point.y + point.height / 2, { steps: 5 }); await page.mouse.up();
    await saved("已移动 2 个关键帧");
    assert.deepEqual(Object.keys((await read()).bones.body.rotation).map(Number).sort(), [0, 0.5, 1]);
    assert.deepEqual((await read()).sound_effects, source.sound_effects);
    assert.deepEqual((await read()).bones.body.position, source.bones.body.position);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1180, 800));
    await page.screenshot({ path: artifactPath("outputs/multiselect-1180.png") });
    await page.getByRole("button", { name: "animation.batch", exact: true }).click();
    await frame(0).waitFor(); await count(0);
    assert.deepEqual((await read()).bones.body.rotation["0.50"], expression);
    assert.deepEqual(errors, []);
    console.log("PASS Ctrl/Shift 多选、冲突与负时间拒绝、写入失败不改状态、批量移动/拖动/复制/粘贴/删除、撤销重做与重开");
    console.log(artifactRoot);
  } catch (error) { if (page) await page.screenshot({ path: artifactPath("outputs/failure.png") }).catch(() => {}); throw error; }
  finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
