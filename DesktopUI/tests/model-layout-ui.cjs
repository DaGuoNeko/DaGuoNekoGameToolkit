const { _electron: electron } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { artifactPath, artifactRoot } = require("./fixtures/artifacts.cjs");

(async () => {
  const data = artifactPath("data"), folder = path.join(data, "model-studio", "layout");
  await fs.mkdir(folder, { recursive: true });
  const geometry = { "minecraft:geometry": [{ description: { identifier: "geometry.layout", texture_width: 64, texture_height: 64 }, bones: [{ name: "body", pivot: [0, 6, 0], cubes: [{ origin: [-4, 0, -2], size: [8, 12, 4], uv: [0, 0] }] }] }] };
  const file = path.join(folder, "model.geo.json"); await fs.writeFile(file, JSON.stringify(geometry), "utf8");
  const animation = { animation_length: 2, loop: true, bones: { body: { rotation: { "0": [0, 0, 0], "1": [0, 30, 0] } } } };
  await fs.writeFile(path.join(folder, "model.animation.json"), JSON.stringify({ animations: { "animation.layout": animation } }), "utf8");
  const env = { ...process.env, DGN_GAME_HEADLESS: "1", DGN_GAME_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  const launch = () => electron.launch({ cwd: path.join(__dirname, ".."), env, ...(process.env.DGN_GAME_TEST_EXE ? { executablePath: process.env.DGN_GAME_TEST_EXE, args: [] } : { args: ["."] }) });
  const app = await launch(); let page;
  const errors = [];
  const capture = async name => {
    await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.show(); win.focus(); win.webContents.invalidate(); });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const png = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString("base64"));
    await fs.writeFile(artifactPath("outputs/" + name + ".png"), Buffer.from(png, "base64"));
  };
  try {
    page = await app.firstWindow(); page.setDefaultTimeout(15000); page.on("pageerror", error => errors.push(error.message));
    await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.webContents.setBackgroundThrottling(false); win.setSize(1440, 900); win.show(); win.focus(); });
    await page.getByRole("heading", { name: "存档", exact: true }).waitFor();
    await page.getByRole("button", { name: "模组与资源", exact: true }).click();
    await page.getByRole("button", { name: "模型制作", exact: true }).click();
    const open = async () => { await page.locator(".model-library-open").filter({ hasText: "geometry.layout" }).click(); await page.getByRole("heading", { name: "大纲", exact: true }).waitFor(); };
    await open();
    const separator = name => page.getByRole("separator", { name, exact: true });
    const left = separator("调整左侧面板宽度"), right = separator("调整右侧面板宽度");
    const number = node => node.getAttribute("aria-valuenow").then(Number);
    const expectValue = async (name, expected) => page.waitForFunction(({ name, expected }) => Math.abs(Number(document.querySelector('[role="separator"][aria-label="' + name + '"]').getAttribute("aria-valuenow")) - expected) <= 1, { name, expected });
    const drag = async (node, dx, dy = 0, cancel = "") => {
      const rect = await node.boundingBox();
      await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2); await page.mouse.down();
      await page.mouse.move(rect.x + rect.width / 2 + dx, rect.y + rect.height / 2 + dy, { steps: 8 });
      if (cancel === "escape") await page.keyboard.press("Escape");
      if (cancel === "pointer") await node.dispatchEvent("pointercancel");
      await page.mouse.up();
    };
    assert.equal(await number(left), 280); assert.equal(await number(right), 280);
    await page.getByRole("button", { name: "body 立方体 1", exact: true }).click();
    await drag(left, 60); await expectValue("调整左侧面板宽度", 340);
    await drag(right, 40); await expectValue("调整右侧面板宽度", 240);
    const horizontal = separator("调整大纲与 UV 高度");
    const top = await number(horizontal); await drag(horizontal, 0, -60); await expectValue("调整大纲与 UV 高度", top - 60);
    assert.ok(Math.abs(await number(separator("调整贴图与元素高度")) - (top - 60)) <= 1);
    await drag(left, 50, 0, "escape"); await expectValue("调整左侧面板宽度", 340);
    await drag(right, -30, 0, "pointer"); await expectValue("调整右侧面板宽度", 240);
    await left.focus(); await left.press("ArrowRight"); await expectValue("调整左侧面板宽度", 350);
    await left.press("Shift+ArrowLeft"); await expectValue("调整左侧面板宽度", 310);
    assert.equal(await page.getByLabel("起点X", { exact: true }).inputValue(), "-4", "分隔条方向键不能移动模型");
    await capture("edit-resized-1440");
    console.log("PASS 编辑分隔条、取消和键盘");
    await page.getByRole("button", { name: "退出编辑", exact: true }).click(); await open();
    await expectValue("调整左侧面板宽度", 310); await expectValue("调整右侧面板宽度", 240);
    await page.getByRole("button", { name: "UI 编辑器", exact: true }).click();
    await page.getByRole("button", { name: "模型制作", exact: true }).click(); await open();
    await expectValue("调整左侧面板宽度", 310);
    await page.getByRole("button", { name: "绘制", exact: true }).click();
    await expectValue("调整左侧面板宽度", 280);
    assert.equal(await page.getByRole("separator", { name: /高度/ }).count(), 0);
    await drag(left, 40); await expectValue("调整左侧面板宽度", 320);
    await page.getByLabel("新贴图名").fill("ink"); await page.getByRole("button", { name: "新建", exact: true }).click();
    await page.getByRole("button", { name: "ink.png", exact: true }).waitFor();
    await page.waitForFunction(() => { const node = document.querySelector('.model-paint canvas'); return node && node.getContext('2d').getImageData(node.width / 2, node.height / 2, 1, 1).data[3] === 255; });
    await page.getByLabel("画笔颜色").fill("#cc3333");
    const paint = page.locator('.model-paint canvas'); const box = await paint.boundingBox();
    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
    const brush = page.locator('.model-brush');
    assert.equal(await brush.getByRole("button", { name: "放弃", exact: true }).isEnabled(), true);
    await page.getByRole("button", { name: "立体", exact: true }).click();
    await expectValue("调整左侧面板宽度", 280);
    const split = separator("调整预览与画板高度"), solidTop = await number(split);
    await drag(split, 0, -40); await expectValue("调整预览与画板高度", solidTop - 40);
    await drag(left, 30); await expectValue("调整左侧面板宽度", 310);
    await page.getByRole("button", { name: "恢复布局", exact: true }).click();
    await expectValue("调整左侧面板宽度", 280); await expectValue("调整预览与画板高度", solidTop);
    assert.equal(await brush.getByRole("button", { name: "放弃", exact: true }).isEnabled(), true, "恢复布局不能丢掉未保存笔画");
    await brush.getByRole("button", { name: "保存贴图", exact: true }).click();
    await page.waitForFunction(() => { const buttons = [...document.querySelectorAll('.model-brush button')]; return buttons.some(button => button.textContent.trim() === "放弃" && button.disabled) && buttons.some(button => button.textContent.trim() === "保存贴图" && !button.disabled); });
    await page.getByRole("button", { name: "立体", exact: true }).click(); await expectValue("调整左侧面板宽度", 320);
    await page.getByRole("button", { name: "动画", exact: true }).click();
    await expectValue("调整左侧面板宽度", 280);
    const timeline = separator("调整时间轴高度"), animTop = await number(timeline);
    await timeline.focus(); await timeline.press("ArrowUp"); await expectValue("调整时间轴高度", animTop - 10);
    await timeline.press("Home"); assert.equal(await number(timeline), Number(await timeline.getAttribute("aria-valuemin")));
    await timeline.press("End"); assert.equal(await number(timeline), Number(await timeline.getAttribute("aria-valuemax")));
    await page.getByRole("button", { name: "恢复布局", exact: true }).click();
    await expectValue("调整时间轴高度", animTop);
    await capture("animation-resized-1440");
    console.log("PASS 四模式布局记忆、未保存笔画和恢复");
    await page.getByRole("button", { name: "编辑", exact: true }).click(); await expectValue("调整左侧面板宽度", 310);
    await left.focus(); await left.press("End");
    await right.focus(); await right.press("End");
    const wideLeft = await number(left), wideRight = await number(right);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 650));
    await page.waitForFunction(() => document.querySelector('.model-bench').clientWidth < 800);
    await page.waitForFunction(() => {
      const bench = document.querySelector('.model-bench'), stage = document.querySelector('.model-stage');
      return stage.getBoundingClientRect().width >= 239 && document.querySelector('.model-props').getBoundingClientRect().right <= bench.getBoundingClientRect().right + 1;
    });
    const fit = await page.evaluate(() => { const a = document.querySelector('.model-bench').getBoundingClientRect(), b = document.querySelector('.model-stage').getBoundingClientRect(), c = document.querySelector('.model-props').getBoundingClientRect(); return { center: b.width, right: c.right, end: a.right, height: b.height }; });
    assert.ok(fit.center >= 239 && fit.height > 150); assert.ok(fit.right <= fit.end + 1);
    await page.getByRole("button", { name: "body 立方体 1", exact: true }).click();
    assert.equal(await page.getByLabel("贴图宽", { exact: true }).inputValue(), "64");
    const textureWidth = await page.getByLabel("贴图宽", { exact: true }).boundingBox();
    assert.ok(textureWidth.width >= 60, "窄面板的尺寸输入应有足够宽度");
    await capture("edit-small-900");
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 900));
    await expectValue("调整左侧面板宽度", wideLeft); await expectValue("调整右侧面板宽度", wideRight);
    await page.getByRole("button", { name: "恢复布局", exact: true }).click(); await expectValue("调整左侧面板宽度", 280);
    assert.deepEqual(JSON.parse(await fs.readFile(file, "utf8")), geometry);
    assert.deepEqual(errors, []);
    console.log("PASS 分隔条拖动/取消/键盘，分模式记忆与切页重开，小窗口限幅及恢复，未保存笔画保留"); console.log(artifactRoot);
  } catch (error) { console.error(error); if (page) await capture("failure").catch(() => {}); throw error; }
  finally { const stop = setTimeout(() => app.process().kill(), 5000); try { await app.close(); } finally { clearTimeout(stop); } }
})().catch(error => { console.error(error); process.exitCode = 1; });
