const { _electron: electron } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { artifactPath, artifactRoot } = require("./fixtures/artifacts.cjs");

(async () => {
  const data = artifactPath("data"), folder = path.join(data, "model-studio", "multi");
  await fs.mkdir(folder, { recursive: true });
  await fs.writeFile(path.join(folder, "model.geo.json"), JSON.stringify({ "minecraft:geometry": [{ description: { identifier: "geometry.multi", texture_width: 64, texture_height: 64 }, bones: [
    { name: "body", pivot: [0, 6, 0], cubes: [{ origin: [-4, 0, -2], size: [8, 12, 4], uv: [0, 0] }] },
    { name: "arm", parent: "body", pivot: [5, 10, 0], cubes: [{ origin: [4, 3, -2], size: [3, 7, 4], uv: [0, 0] }] },
  ] }] }), "utf8");
  const expression = { pre: [1, 2, 3], post: ["q.anim_time * 20", 0, 0], lerp_mode: "catmullrom", extra: "keep" };
  const source = { loop: false, animation_length: 5, sound_effects: { "0": { effect: "fixture" } }, bones: {
    body: { rotation: { "0": [0, 0, 0], "0.5": expression, "2.00": [10, 20, 30] }, position: { "0.00": [0, 1, 0] } },
    arm: { rotation: { "0.00": [0, 5, 0], "0.25": [0, 7, 0] } },
  } };
  const target = { animation_length: 5, loop: false, bones: {}, timeline: { 0: "keep" } };
  const file = path.join(folder, "model.animation.json");
  await fs.writeFile(file, JSON.stringify({ animations: { "animation.multi": source, "animation.target": target } }, null, 2), "utf8");
  const missingFolder = path.join(data, "model-studio", "missing");
  await fs.mkdir(missingFolder);
  await fs.writeFile(path.join(missingFolder, "model.geo.json"), JSON.stringify({ "minecraft:geometry": [{ description: { identifier: "geometry.missing", texture_width: 64, texture_height: 64 }, bones: [{ name: "body", pivot: [0, 0, 0], cubes: [{ origin: [-4, 0, -2], size: [8, 12, 4], uv: [0, 0] }] }] }] }), "utf8");
  const missingFile = path.join(missingFolder, "model.animation.json");
  const missingContent = JSON.stringify({ animations: { "animation.empty": target } });
  await fs.writeFile(missingFile, missingContent, "utf8");
  const env = { ...process.env, DGN_GAME_HEADLESS: "1", DGN_GAME_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ cwd: path.join(__dirname, ".."), env, ...(process.env.DGN_GAME_TEST_EXE ? { executablePath: process.env.DGN_GAME_TEST_EXE, args: [] } : { args: ["."] }) });
  let page;
  const errors = [];
  const read = async () => JSON.parse(await fs.readFile(file, "utf8")).animations;
  try {
    page = await app.firstWindow(); page.setDefaultTimeout(15000);
    page.on("pageerror", error => errors.push(error.message));
    await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.webContents.setBackgroundThrottling(false); win.setSize(1440, 900); win.show(); win.focus(); });
    await page.getByRole("heading", { name: "存档", exact: true }).waitFor();
    await page.getByRole("button", { name: "模组与资源", exact: true }).click();
    await page.getByRole("button", { name: "模型制作", exact: true }).click();
    await page.locator(".model-library-open").filter({ hasText: "geometry.multi" }).click();
    await page.getByRole("button", { name: "动画", exact: true }).click();
    await page.getByRole("button", { name: "animation.multi", exact: true }).click();
    await page.locator(".model-bone-list").getByRole("button", { name: "body", exact: true }).click();
    const timeline = page.locator(".model-timeline");
    const frame = (bone, channel, at) => page.getByRole("group", { name: "关键帧轨道 " + bone + " " + channel, exact: true }).getByRole("button", { name: "关键帧 " + channel + " " + at.toFixed(2), exact: true });
    const count = value => page.waitForFunction(value => document.querySelector('[aria-label="关键帧选择"]').textContent === "已选 " + value + " 帧", value);
    const saved = async message => { await page.getByText(message, { exact: true }).waitFor(); await page.waitForFunction(() => !document.querySelector('[aria-label="关键帧选择"]').textContent.includes("保存中")); };
    const selectMixed = async offset => {
      await frame("body", "旋转", 0.5 + offset).click();
      await frame("body", "位移", offset).click({ modifiers: ["Control"] });
      await frame("arm", "旋转", offset).click({ modifiers: ["Control"] });
      await count(3);
    };
    await frame("body", "旋转", 0).click();
    await frame("body", "旋转", 0.5).click({ modifiers: ["Shift"] }); await count(2);
    await frame("arm", "旋转", 0).click({ modifiers: ["Control"] }); await count(3);
    await frame("body", "位移", 0).click({ modifiers: ["Control"] }); await count(4);
    await frame("body", "旋转", 0).click({ modifiers: ["Control"] }); await count(3);
    assert.equal(await frame("body", "旋转", 0.5).getAttribute("aria-pressed"), "true");
    assert.equal(await frame("arm", "旋转", 0).getAttribute("aria-pressed"), "true");
    await page.getByText("跨 3 条轨道", { exact: true }).waitFor();
    await page.screenshot({ path: artifactPath("outputs/mixed-selection-1440.png") });
    await page.getByLabel("关键帧偏移秒数").fill("0.25");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click();
    await page.getByText("目标时间已有关键帧，未覆盖任何帧", { exact: true }).waitFor();
    assert.deepEqual((await read())["animation.multi"], source);
    await page.getByLabel("关键帧偏移秒数").fill("-0.25");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click();
    await page.getByText("关键帧时间必须在 0–10000 秒之间", { exact: true }).waitFor();
    assert.deepEqual((await read())["animation.multi"], source);
    await page.getByLabel("关键帧偏移秒数").fill("0.5");
    await fs.mkdir(file + ".bak");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click();
    await page.getByText(/EISDIR|EPERM|illegal operation|operation not permitted/).waitFor();
    assert.deepEqual((await read())["animation.multi"], source); await count(3);
    assert.equal(await timeline.getByRole("button", { name: "撤销", exact: true }).isDisabled(), true);
    await fs.rmdir(file + ".bak");
    await timeline.getByRole("button", { name: "移动所选", exact: true }).click(); await saved("已移动 3 个关键帧");
    let current = (await read())["animation.multi"];
    assert.deepEqual(current.bones.body.rotation["1.00"], expression);
    assert.deepEqual(current.bones.body.position["0.50"], [0, 1, 0]);
    assert.deepEqual(current.bones.arm.rotation["0.50"], [0, 5, 0]);
    await timeline.getByRole("button", { name: "撤销", exact: true }).click(); await saved("已撤销");
    assert.deepEqual((await read())["animation.multi"], source);
    await timeline.getByRole("button", { name: "重做", exact: true }).click(); await saved("已重做");
    await selectMixed(0.5);
    await frame("body", "旋转", 1).scrollIntoViewIfNeeded();
    const point = await frame("body", "旋转", 1).boundingBox();
    const track = await frame("body", "旋转", 1).locator("..").boundingBox();
    await page.mouse.move(point.x + point.width / 2, point.y + point.height / 2); await page.mouse.down();
    await page.mouse.move(point.x + point.width / 2 - (track.width - 12) * 0.5 / 5, point.y + point.height / 2, { steps: 5 }); await page.mouse.up();
    await saved("已移动 3 个关键帧");
    current = (await read())["animation.multi"];
    assert.deepEqual(current.bones.body.rotation["0.50"], expression);
    assert.deepEqual(current.bones.body.position["0.00"], [0, 1, 0]);
    assert.deepEqual(current.bones.arm.rotation["0.00"], [0, 5, 0]);
    assert.deepEqual(current.bones.arm.rotation["0.25"], [0, 7, 0]);
    await timeline.getByRole("button", { name: "复制", exact: true }).click();
    await saved("已复制 3 个关键帧");
    const slider = page.getByRole("slider", { name: "时间", exact: true });
    const seek = async seconds => {
      const rect = await slider.boundingBox();
      await slider.click({ position: { x: 8 + (rect.width - 16) * seconds / 5, y: rect.height / 2 } });
      const at = Number(await slider.inputValue());
      assert.ok(Math.abs(at - seconds) <= 0.1);
      await page.waitForFunction(value => document.querySelector('.model-timeline > .model-texture-note').textContent.startsWith(value.toFixed(2) + " /"), at);
      return at;
    };
    const pasteAt = await seek(3);
    const pasteStart = pasteAt.toFixed(2), pasteEnd = (pasteAt + 0.5).toFixed(2);
    await timeline.getByRole("button", { name: "粘贴", exact: true }).click(); await saved("已粘贴 3 个关键帧");
    current = (await read())["animation.multi"];
    assert.deepEqual(current.bones.body.rotation[pasteEnd], expression);
    assert.deepEqual(current.bones.body.position[pasteStart], [0, 1, 0]);
    assert.deepEqual(current.bones.arm.rotation[pasteStart], [0, 5, 0]);
    await timeline.getByRole("button", { name: "删除所选", exact: true }).click(); await saved("已删除 3 个关键帧");
    current = (await read())["animation.multi"];
    assert.equal(current.bones.body.rotation[pasteEnd], undefined);
    assert.equal(current.bones.body.position[pasteStart], undefined);
    assert.equal(current.bones.arm.rotation[pasteStart], undefined);
    assert.deepEqual(current.sound_effects, source.sound_effects);
    await page.getByRole("button", { name: "animation.target", exact: true }).click(); await count(0);
    await page.waitForFunction(() => document.querySelector('.model-anim-list button.active')?.textContent === "animation.target");
    await page.locator(".model-bone-list").getByRole("button", { name: "arm", exact: true }).click();
    const targetAt = await seek(2);
    const targetStart = targetAt.toFixed(2), targetEnd = (targetAt + 0.5).toFixed(2);
    await timeline.getByRole("button", { name: "粘贴", exact: true }).click(); await saved("已粘贴 3 个关键帧");
    const pasted = (await read())["animation.target"];
    assert.deepEqual(pasted.bones.body.rotation[targetEnd], expression);
    assert.deepEqual(pasted.bones.body.position[targetStart], [0, 1, 0]);
    assert.deepEqual(pasted.bones.arm.rotation[targetStart], [0, 5, 0]);
    assert.deepEqual(pasted.timeline, target.timeline);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1180, 800));
    await page.screenshot({ path: artifactPath("outputs/mixed-paste-1180.png") });
    await page.getByRole("button", { name: "animation.target", exact: true }).click(); await count(0);
    await frame("body", "旋转", Number(targetEnd)).waitFor(); await frame("arm", "旋转", targetAt).waitFor();
    await page.getByRole("button", { name: "退出编辑", exact: true }).click();
    await page.locator(".model-library-open").filter({ hasText: "geometry.missing" }).click();
    await page.getByRole("button", { name: "动画", exact: true }).click();
    await page.getByRole("button", { name: "animation.empty", exact: true }).click();
    await page.locator(".model-bone-list").getByRole("button", { name: "body", exact: true }).click();
    await timeline.getByRole("button", { name: "粘贴", exact: true }).click();
    await page.getByText("目标模型缺少骨骼 arm，未粘贴任何帧", { exact: true }).waitFor();
    assert.equal(await fs.readFile(missingFile, "utf8"), missingContent);
    assert.equal(await timeline.getByRole("button", { name: "撤销", exact: true }).isDisabled(), true);
    assert.deepEqual(errors, []);
    console.log("PASS 跨骨骼/通道 Ctrl 多选、混合拖动/偏移/复制/粘贴/删除、冲突与写入失败全组回退、撤销重做、跨动画粘贴和重开");
    console.log(artifactRoot);
  } catch (error) { if (page) await page.screenshot({ path: artifactPath("outputs/failure.png") }).catch(() => {}); throw error; }
  finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
