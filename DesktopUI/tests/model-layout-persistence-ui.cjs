const { _electron: electron } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { WorkspaceStore } = require("../electron/services.cjs");
const { Profiles } = require("../electron/domains/profiles/profiles.cjs");
const { defaultLayout } = require("../shared/model-layout.cjs");
const { artifactPath, artifactRoot } = require("./fixtures/artifacts.cjs");

(async () => {
  const data = artifactPath("data"), folder = path.join(data, "model-studio", "persistent");
  await fs.mkdir(folder, { recursive: true });
  const file = path.join(folder, "model.geo.json");
  await fs.writeFile(file, JSON.stringify({ "minecraft:geometry": [{ description: { identifier: "geometry.persistent", texture_width: 64, texture_height: 64 }, bones: [{ name: "body", pivot: [0, 6, 0], cubes: [{ origin: [-4, 0, -2], size: [8, 12, 4], uv: [0, 0] }] }] }] }), "utf8");
  const originalModel = await fs.readFile(file, "utf8");
  const store = new WorkspaceStore(data); await store.load(); await store.updateSettings({ AppearanceMode: "Dark", ThemeHue: 210 });
  await new Profiles(store).initialize();
  const settingsFile = path.join(data, "settings.json");
  const disk = JSON.parse(await fs.readFile(settingsFile, "utf8"));
  disk.settings.ModelStudioLayouts = { edit: { left: "invalid" }, paint: { left: 300, right: 280, split: 0.55 } };
  disk.settings.futureOption = { keep: 42 }; disk.extension = "keep";
  await fs.writeFile(settingsFile, JSON.stringify(disk), "utf8");
  const env = { ...process.env, DGN_GAME_HEADLESS: "1", DGN_GAME_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  let app, page; const errors = [];
  const launch = async () => {
    app = await electron.launch({ cwd: path.join(__dirname, ".."), env, ...(process.env.DGN_GAME_TEST_EXE ? { executablePath: process.env.DGN_GAME_TEST_EXE, args: [] } : { args: ["."] }) });
    page = await app.firstWindow(); page.setDefaultTimeout(15000); page.on("pageerror", error => errors.push(error.message));
    await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.webContents.setBackgroundThrottling(false); win.setSize(1440, 900); win.show(); win.focus(); });
    await page.getByRole("heading", { name: "存档", exact: true }).waitFor();
    await page.getByRole("button", { name: "模组与资源", exact: true }).click();
    await page.getByRole("button", { name: "模型制作", exact: true }).click();
    await page.locator('.model-library-open').filter({ hasText: "geometry.persistent" }).click();
    await saved();
  };
  const saved = () => page.waitForFunction(() => document.querySelector('[aria-label="布局保存状态"]')?.textContent === "布局已保存");
  const left = () => page.getByRole("separator", { name: "调整左侧面板宽度", exact: true });
  const value = async () => Number(await left().getAttribute("aria-valuenow"));
  const expectWidth = async width => page.waitForFunction(width => Number(document.querySelector('[aria-label="调整左侧面板宽度"]').getAttribute("aria-valuenow")) === width, width);
  const resize = async delta => {
    const before = await value();
    const rect = await left().boundingBox();
    await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2); await page.mouse.down();
    await page.mouse.move(rect.x + rect.width / 2 + delta, rect.y + rect.height / 2, { steps: 5 }); await page.mouse.up();
    await expectWidth(before + delta);
  };
  const read = async () => JSON.parse(await fs.readFile(settingsFile, "utf8"));
  const close = async () => { if (!app) return; const instance = app; app = null; const timer = setTimeout(() => instance.process().kill(), 5000); try { await instance.close(); } finally { clearTimeout(timer); } };
  const capture = async name => {
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const png = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString("base64"));
    await fs.writeFile(artifactPath("outputs/" + name + ".png"), Buffer.from(png, "base64"));
  };
  try {
    await launch(); await expectWidth(280);
    assert.deepEqual((await read()).settings.ModelStudioLayouts.edit, { left: "invalid" }, "读取不能重写损坏的原始字段");
    await resize(40); await saved();
    const first = (await read()).settings.ModelStudioLayouts.edit;
    assert.equal(first.left, 320);
    assert.deepEqual(JSON.parse(await fs.readFile(settingsFile + ".bak", "utf8")).settings.ModelStudioLayouts.edit, { left: "invalid" });
    await page.getByRole("button", { name: "绘制", exact: true }).click(); await expectWidth(300);
    await resize(30); await saved();
    await page.getByRole("button", { name: "立体", exact: true }).click(); await expectWidth(280);
    await resize(60); await saved();
    await page.getByRole("button", { name: "动画", exact: true }).click(); await expectWidth(280);
    await resize(70); await saved();
    const all = (await read()).settings.ModelStudioLayouts;
    assert.deepEqual(Object.keys(all).sort(), ["animate", "edit", "paint", "solid"]);
    assert.equal(all.solid.left, 340); assert.equal(all.animate.left, 350);
    await page.getByRole("button", { name: "编辑", exact: true }).click(); await expectWidth(320);
    const beforeFailure = await fs.readFile(settingsFile, "utf8");
    await fs.unlink(settingsFile + ".bak"); await fs.mkdir(settingsFile + ".bak");
    await resize(10);
    await page.getByRole("button", { name: "重试布局保存", exact: true }).waitFor();
    assert.ok((await page.getByRole("status", { name: "布局保存状态" }).innerText()).includes("布局保存失败"));
    assert.equal(await fs.readFile(settingsFile, "utf8"), beforeFailure);
    await expectWidth(330);
    await capture("save-failure");
    await fs.rmdir(settingsFile + ".bak");
    await page.getByRole("button", { name: "重试布局保存", exact: true }).click(); await saved();
    assert.equal((await read()).settings.ModelStudioLayouts.edit.left, 330);
    await left().focus(); await left().press("ArrowRight"); await expectWidth(340);
    await left().press("ArrowRight"); await expectWidth(350);
    await left().press("ArrowLeft"); await expectWidth(340); await saved();
    await close(); await launch(); await expectWidth(340);
    await page.getByRole("button", { name: "绘制", exact: true }).click(); await expectWidth(330);
    await page.getByRole("button", { name: "立体", exact: true }).click(); await expectWidth(340);
    await page.getByRole("button", { name: "动画", exact: true }).click(); await expectWidth(350);
    await page.getByRole("button", { name: "恢复布局", exact: true }).click(); await saved();
    assert.deepEqual((await read()).settings.ModelStudioLayouts.animate, defaultLayout("animate"));
    assert.equal((await read()).settings.ModelStudioLayouts.edit.left, 340);
    await close(); await launch(); await expectWidth(340);
    await page.getByRole("button", { name: "动画", exact: true }).click(); await expectWidth(280);
    await page.getByRole("button", { name: "编辑", exact: true }).click(); await expectWidth(340);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 650));
    await page.waitForFunction(() => document.querySelector('.model-stage').clientWidth >= 238 && document.querySelector('.model-props').getBoundingClientRect().right <= window.innerWidth);
    assert.equal((await read()).settings.ModelStudioLayouts.edit.left, 340, "窗口限幅不能改写用户偏好");
    await capture("restart-small");
    const final = await read(); assert.deepEqual(final.settings.futureOption, { keep: 42 }); assert.equal(final.extension, "keep");
    assert.equal(final.settings.ThemeHue, 210); assert.equal(await fs.readFile(file, "utf8"), originalModel);
    assert.deepEqual(errors, []);
    console.log("PASS 四模式跨重启恢复、持久化重置、真实写入失败与重试、连续键盘保存、异常设置回退及未知字段保留"); console.log(artifactRoot);
  } catch (error) { console.error(error); if (page && app) await capture("failure").catch(() => {}); throw error; }
  finally { await close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
