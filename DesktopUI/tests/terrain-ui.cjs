const { _electron: electron } = require("playwright");
const fs = require("node:fs/promises"), path = require("node:path"), os = require("node:os"), assert = require("node:assert/strict");
const { spawnSync } = require("node:child_process");
const { WorkspaceStore } = require("../electron/services.cjs");
const { Profiles } = require("../electron/domains/profiles/profiles.cjs");
const { WorldLibrary } = require("../electron/domains/worlds/worlds.cjs");
const { artifactRoot, testResultsRoot } = require("./fixtures/artifacts.cjs");
const { bedrockMap } = require("./fixtures/map-world.cjs");
(async () => {
  const root = await fs.mkdtemp(path.join(artifactRoot, "data-"));
  let app;
  try {
    const data = path.join(root, "data"), source = path.join(root, "source"), game = path.join(root, "Game.exe"), launcher = path.join(root, "Launcher.exe");
    await bedrockMap(source);
    await fs.writeFile(game, "fixture only");
    const cs = path.join(root, "Fixture.cs");
    await fs.writeFile(cs, `using System;using System.Diagnostics;class Fixture{static void Main(){var p=new Process();p.StartInfo=new ProcessStartInfo(${JSON.stringify(process.execPath)},${JSON.stringify('"' + path.resolve("tests/fixtures/debug-runtime.cjs") + '"')});p.StartInfo.UseShellExecute=false;p.StartInfo.CreateNoWindow=true;p.StartInfo.RedirectStandardOutput=true;p.StartInfo.RedirectStandardError=true;p.OutputDataReceived+=(s,e)=>{if(e.Data!=null)Console.WriteLine(e.Data);};p.ErrorDataReceived+=(s,e)=>{if(e.Data!=null)Console.Error.WriteLine(e.Data);};p.Start();p.BeginOutputReadLine();p.BeginErrorReadLine();p.WaitForExit();}}`);
    const c = spawnSync(path.join(process.env.WINDIR, "Microsoft.NET/Framework64/v4.0.30319/csc.exe"), ["/nologo", "/target:exe", "/out:" + launcher, cs], { encoding: "utf8", windowsHide: true });
    assert.equal(c.status, 0, c.stdout + c.stderr);
    const store = new WorkspaceStore(data); await store.load();
    const profiles = new Profiles(store); await profiles.initialize();
    await store.updateSettings({ GamePath: game, LauncherPath: launcher });
    const profile = await profiles.read(store.value.projects[0].id);
    const worlds = new WorldLibrary(store, path.join(data, "game-data/MinecraftPE_Netease/minecraftWorlds"));
    const world = await worlds.create(profile.project.id, { name: "目标地图" });
    await bedrockMap(worlds.location(world.id));
    app = await electron.launch({ args: ["tests/fixtures/multi-hosts-ui-entry.cjs"], env: { ...process.env, DGN_GAME_HEADLESS: "1", DGN_GAME_DATA_DIR: data } });
    const page = await app.firstWindow(); page.setDefaultTimeout(20000);
    await page.emulateMedia({ reducedMotion: "reduce" });
    const errors = []; page.on("pageerror", e => errors.push(e.message));
    await app.evaluate(({ dialog, BrowserWindow }, file) => {
      BrowserWindow.getAllWindows()[0].webContents.setBackgroundThrottling(false);
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] });
    }, source);
    const ipc = (method, args = {}) => page.evaluate(({ method, args }) => window.toolkit.call(method, args), { method, args });
    async function poll(predicate) {
      const end = Date.now() + 30000;
      while (Date.now() < end) {
        if (await predicate()) return;
        await new Promise(resolve => setTimeout(resolve, 100));
      }
      throw Error('terrain UI state timeout: ' + JSON.stringify(await ipc('architecture.state')));
    }
    await page.getByRole("article", { name: "存档 目标地图", exact: true }).getByRole("button", { name: "启动此存档", exact: true }).click();
    await page.getByText("调试已就绪", { exact: true }).waitFor();
    const state = await ipc("launch.state");
    assert.equal(await page.getByRole("button", { name: "地形与建筑导入", exact: true }).count(), 1);
    await page.getByRole("button", { name: "地形与建筑导入", exact: true }).click();
    const panel = page.locator(".workspace-surface").filter({ has: page.getByRole("heading", { name: "地形与建筑导入", exact: true }) });
    await panel.getByRole("combobox", { name: "来源类型", exact: true }).click();
    await page.getByRole("option", { name: "基岩世界 · 文件夹 / MCWORLD / ZIP", exact: true }).click();
    await panel.getByRole("button", { name: "选择文件夹", exact: true }).click();
    await panel.getByRole("button", { name: "在来源地图框选区域", exact: true }).click();
    const sourceMap = page.locator("dialog").filter({ has: page.getByRole("heading", { name: "在地图上框选来源区域", exact: true }) }).last();
    await sourceMap.getByText(/范围 X/).waitFor();
    const canvas = sourceMap.getByLabel("地图画布", { exact: true });
    const box = await canvas.boundingBox();
    await page.mouse.move(box.x + box.width / 2 - 60, box.y + box.height / 2 - 30);
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 20, box.y + box.height / 2 + 30, { steps: 5 }); await page.mouse.up();
    const picked = (await sourceMap.locator(".map-preview-selection").innerText()).match(/选区 X (-?\d+)～(-?\d+)，Z (-?\d+)～(-?\d+)/);
    assert(picked, "source map must show an explicit rectangle");
    await page.screenshot({ path: path.join(testResultsRoot, "terrain-map-selection.png") });
    await sourceMap.getByRole("button", { name: "使用此选区", exact: true }).click();
    assert.equal(await panel.locator('input[aria-label="角点一 X"]').inputValue(), picked[1]);
    assert.equal(await panel.locator('input[aria-label="角点二 Z"]').inputValue(), picked[4]);
    for (const [name, value] of [["角点一 X", "-2"], ["角点一 Y", "64"], ["角点一 Z", "0"], ["角点二 X", "-1"], ["角点二 Y", "64"], ["角点二 Z", "0"]]) await panel.locator(`input[aria-label="${name}"]`).fill(value);
    await panel.getByRole("button", { name: "下一步：目标与落点", exact: true }).click();
    await panel.getByRole("button", { name: "在目标地图选择落点", exact: true }).click();
    const targetMap = page.locator("dialog").filter({ has: page.getByRole("heading", { name: "在地图上选择目标落点", exact: true }) }).last();
    await targetMap.getByText(/范围 X/).waitFor();
    await targetMap.getByLabel("地图画布", { exact: true }).click({ position: { x: 170, y: 150 } });
    await targetMap.getByRole("button", { name: "使用此落点", exact: true }).click();
    assert.notEqual(await panel.locator('input[aria-label="目标原点 X"]').inputValue(), "0");
    await panel.getByLabel("目标维度 ID", { exact: true }).fill("3");
    await poll(async () => panel.getByText("下一步：保存与切换", { exact: true }).isVisible());
    assert((await ipc("launch.state")).sessions.find(s => s.id === state.selectedSession).running, "planning must not stop the target");
    assert.equal(await ipc("architecture.state"), null, "planning must not create a running task");
    await panel.getByRole("button", { name: "下一步：保存与切换", exact: true }).click();
    const confirmation = page.locator("dialog").filter({ has: page.getByRole("heading", { name: "确认保存与切换", exact: true }) }).last();
    await confirmation.getByRole("button", { name: "返回规划", exact: true }).click();
    assert((await ipc("launch.state")).sessions.find(s => s.id === state.selectedSession).running, "cancel keeps target running");
    await panel.getByRole("button", { name: "下一步：保存与切换", exact: true }).click();
    await confirmation.getByRole("checkbox").check();
    await fs.mkdir(testResultsRoot, { recursive: true });
    await page.screenshot({ path: path.join(testResultsRoot, "terrain-source-light.png") });
    await confirmation.getByRole("button", { name: "准备来源副本", exact: true }).click();
    const stage = expected => poll(async () => { const task = await ipc('architecture.state'); if (task?.error) throw Error(task.error); return task?.stage === expected && !task.busy; });
    await stage("prepared");
    assert.equal((await ipc("architecture.state")).planning.targetDimension, 3);
    const savedPlan = (await ipc("architecture.state")).planning;
    await panel.getByRole("button", { name: "收起", exact: true }).click();
    await page.getByRole("button", { name: "地形与建筑导入", exact: true }).click();
    await panel.getByRole("button", { name: "启动来源世界", exact: true }).waitFor();
    assert.equal(await panel.locator('input[aria-label="角点一 X"]').inputValue(), String(savedPlan.x1), "reopening restores the source plan");
    await panel.getByRole("button", { name: "启动来源世界", exact: true }).click();
    await stage("source-running");
    await poll(async () => { const t = await ipc("architecture.state"); return (await ipc("world-actions.state", { worldId: t.sourceWorldId })).ready; });
    for (const [name, value] of [["角点一 X", "-2"], ["角点一 Y", "64"], ["角点一 Z", "0"], ["角点二 X", "-1"], ["角点二 Y", "64"], ["角点二 Z", "0"]]) await panel.locator(`input[aria-label="${name}"]`).fill(value);
    await panel.getByRole("button", { name: "读取选区地形", exact: true }).click();
    await stage("source-ready");
    assert.deepEqual((await ipc("architecture.state")).region.min, [-2,64,0]);
    await panel.getByRole("button", { name: "退出来源并备份启动目标", exact: true }).click(); await stage("target-running");
    await poll(async () => (await ipc("world-actions.state", { worldId: world.id })).ready);
    await panel.getByRole("button", { name: "读取当前玩家位置与维度", exact: true }).click();
    await panel.getByText(/当前读取：维度 3/).waitFor();
    await panel.getByRole("button", { name: "检查目标并生成预览", exact: true }).click(); await stage("preview-ready");
    const preview = await ipc("architecture.state");
    assert.equal(preview.plan.counts.changed, 2);
    await page.screenshot({ path: path.join(testResultsRoot, "terrain-preview-light.png") });
    await page.evaluate(() => document.documentElement.setAttribute("data-theme", "dark"));
    await page.screenshot({ path: path.join(testResultsRoot, "terrain-preview-dark.png") });
    await panel.getByRole("button", { name: /确认导入 \d+ 格/, exact: true }).click();
    await page.locator("dialog").filter({ has: page.getByRole("heading", { name: "确认写入目标区域", exact: true }) }).last().getByRole("button", { name: "开始导入", exact: true }).click(); await stage("done");
    await panel.getByRole("button", { name: "撤销本次导入", exact: true }).click();
    await page.locator("dialog").filter({ has: page.getByRole("heading", { name: "确认撤销本次导入", exact: true }) }).last().getByRole("button", { name: "开始撤销", exact: true }).click(); await stage("undone");
    await panel.getByRole("button", { name: "收起", exact: true }).click();
    await page.getByRole("button", { name: "地图预览", exact: true }).click();
    const map = page.locator(".workspace-surface").filter({ has: page.getByRole("heading", { name: "地图预览", exact: true }) });
    await map.getByText(/范围 X/).waitFor();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 650));
    const selectionCanvas = map.getByLabel("地图画布", { exact: true });
    // 小窗口中的工作区可滚动，原生拖动必须落在可见画布内。
    await selectionCanvas.scrollIntoViewIfNeeded();
    const bounds = await selectionCanvas.boundingBox();
    assert(await selectionCanvas.evaluate(c => { const b = c.getBoundingClientRect(); return document.elementFromPoint(b.x + b.width * .4, b.y + b.height * .4) === c; }), "selection starts on the visible canvas");
    await page.keyboard.down("Shift");
    await page.mouse.move(bounds.x + bounds.width * .4, bounds.y + bounds.height * .4); await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width * .6, bounds.y + bounds.height * .6, { steps: 5 }); await page.mouse.up(); await page.keyboard.up("Shift");
    await map.getByRole("button", { name: "以此选区为来源", exact: true }).click();
    await panel.getByRole("button", { name: "下一步：目标与落点", exact: true }).click();
    await panel.getByRole("button", { name: "下一步：保存与切换", exact: true }).click();
    await confirmation.getByRole("checkbox").check();
    await confirmation.getByRole("button", { name: "准备来源副本", exact: true }).click();
    await stage("prepared");
    assert.equal((await ipc("architecture.state")).source, worlds.location(world.id), "registered source is resolved by the main process");
    assert.deepEqual(errors, []);
    console.log("PASS terrain UI: map entry, source rectangle, target point, planning without stopping, cancel, consent, persisted plan, source switch, backup, dimension preview, write/undo, registered source copy");
  } catch (error) {
    if (app) {
      const page = await app.firstWindow();
      console.error(await page.locator("dialog[open]").allTextContents());
      await page.screenshot({ path: path.join(testResultsRoot, "terrain-failure.png") });
    }
    throw error;
  } finally {
    if (app) await app.close();
    assert.equal(path.dirname(root), path.resolve(artifactRoot));
    assert(path.basename(root).startsWith("data-"));
    await fs.rm(root, { recursive: true, force: true });
  }
})().catch(e => { console.error(e.stack); process.exitCode = 1; });
